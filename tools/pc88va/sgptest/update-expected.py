"""Regenerate sgptest-expected.inc from vaeg (maintainer-local).

SGPTEST is assembled without expected values, installed on a copy of a
PC-Engine 1.1 system disk (private, never committed) and run headless in
vaeg on the VA and the VA2 model. The CRCs are read from the TVRAM dump at
exit; both models must agree on every test, and the values are written as
the expected values, which the program then compares on hardware.
"""

import argparse
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOOLS = HERE.parent
TESTS = 20
RESULT = re.compile(r"T(\d\d) ([0-9A-F]{4}) ")


def tvram_text(data):
    """Characters of a raw TVRAM dump: the low byte of each 16-bit cell."""
    return "".join(chr(b) if 0x20 <= b < 0x7f else "\n" for b in data[0::2])


def run_model(args, work, model, disk):
    image = work / f"{model}.d88"
    shutil.copyfile(disk, image)
    script = work / "input.txt"
    script.write_text("@wait 1500\n\\vt\\sgptest\n@wait 1200\n")
    dump = work / f"{model}.tvram"
    env = dict(os.environ, SDL_VIDEODRIVER="dummy", SDL_AUDIODRIVER="dummy",
               VAEG_SCREEN_EXIT_MS="60000")
    cfg = work / "vaeg.cfg"
    cfg.write_text("[NekoProjectII]\n")
    subprocess.run([args.vaeg, "--cfg", str(cfg), "--bkupmem", str(work / f"{model}.dat"),
                    "--roms", args.roms, "--model", model, "--mute", "--fdd1", str(image),
                    "--headless-input-script", str(script), "--screen-tvram-dump", str(dump)],
                   env=env, check=False, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                   timeout=600)
    found = {}
    for number, crc in RESULT.findall(tvram_text(dump.read_bytes())):
        found[int(number)] = crc
    missing = [n for n in range(1, TESTS + 1) if n not in found]
    if missing:
        sys.exit(f"{model}: no result for tests {missing}")
    return found


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vaeg", required=True, help="vaeg executable")
    parser.add_argument("--roms", required=True, help="ROM directory")
    parser.add_argument("--pcengine", required=True, help="PC-Engine 1.1 system disk (D88)")
    parser.add_argument("--output", default=str(HERE / "sgptest-expected.inc"))
    args = parser.parse_args()

    with tempfile.TemporaryDirectory(prefix="sgptest-") as name:
        work = Path(name)
        payload = work / "payload" / "VT"
        payload.mkdir(parents=True)
        subprocess.run(["nasm", "-f", "bin", "-DEXPECTED_NONE", "-o", str(payload / "SGPTEST.COM"),
                        str(HERE / "sgptest.asm")], check=True)
        disk = work / "pce.d88"
        disk_tool = [sys.executable, "-I", str(TOOLS / "pcengine_disk.py")]
        subprocess.run(disk_tool + ["vanilla", "--source", args.pcengine, "--output", str(disk)],
                       check=True, stdout=subprocess.DEVNULL)
        subprocess.run(disk_tool + ["install", "--image", str(disk), "--payload",
                                    str(work / "payload")], check=True, stdout=subprocess.DEVNULL)
        results = {model: run_model(args, work, model, disk) for model in ("va", "va2")}

    if results["va"] != results["va2"]:
        differ = [n for n in range(1, TESTS + 1) if results["va"][n] != results["va2"][n]]
        sys.exit(f"VA and VA2 differ in tests {differ}")
    header = (HERE / "sgptest.asm").read_text().split("\n\n", 1)[0]
    lines = [header, "",
             "; Generated by update-expected.py: SGPTEST CRCs from vaeg (VA and VA2",
             "; agree). Regenerate after a deliberate change to SGP behaviour."]
    lines += [f"%define EXP_T{n:02d} 0x{results['va'][n]}" for n in range(1, TESTS + 1)]
    Path(args.output).write_text("\n".join(lines) + "\n")
    print(f"wrote {args.output}")


if __name__ == "__main__":
    main()
