"""Generate sdl2/extrarom_mame.inc from MAME's PC-8801/8001 ROM definitions.

usage: extrarom-mame-table.py MAME_SOURCE_DIR > sdl2/extrarom_mame.inc

MAME_SOURCE_DIR holds pc8001.cpp and pc8801.cpp (src/mame/nec/) and
pc80s31k.cpp (src/devices/bus/nec_fdd/) of a MAME checkout. Only the
published facts are taken: each ROM's SHA-1, its machine, file name, BIOS
label and BAD_DUMP mark. No MAME code is used.
"""

import re
import sys
from pathlib import Path

SOURCES = ("pc8001.cpp", "pc8801.cpp", "pc80s31k.cpp")


def rows(directory):
    seen = set()
    for name in SOURCES:
        driver, bioses = None, {}
        text = (directory / name).read_text(encoding="utf-8", errors="replace")
        for line in text.splitlines():
            if line.lstrip().startswith("//"):
                continue
            m = re.search(r"ROM_START\(\s*(\w+)\s*\)", line)
            if m:
                driver, bioses = m.group(1), {}
                continue
            m = re.search(r'ROM_SYSTEM_BIOS\(\s*(\d+)\s*,\s*"[^"]*"\s*,\s*"([^"]*)"', line)
            if m:
                bioses[m.group(1)] = m.group(2)
                continue
            m = re.search(r'ROMX?_LOAD\w*\(\s*"([^"]+)".*?SHA1\(([0-9a-fA-F]{40})\)', line)
            if not (m and driver):
                continue
            # A BIOS label belongs only to the ROMs loaded with ROM_BIOS(n).
            b = re.search(r"ROM_BIOS\(\s*(\d+)\s*\)", line)
            bios = bioses.get(b.group(1), "") if b else ""
            sha = m.group(2).lower()
            if (sha, driver) in seen:
                continue
            seen.add((sha, driver))
            yield sha, driver, m.group(1), bios, "BAD_DUMP" in line


def main():
    directory = Path(sys.argv[1])
    out = [
        "/* clang-format off */",
        "/* Generated by tools/pc88va/extrarom-mame-table.py; do not edit. */",
        "/* SHA-1, machine, file, BIOS label and BAD_DUMP mark of each ROM in */",
        "/* MAME's " + ", ".join(SOURCES) + ". */",
    ]
    source = directory / "SOURCE.txt"
    if source.exists():
        out.append("/* " + source.read_text(encoding="utf-8").strip().splitlines()[0] + " */")
    for sha, driver, file, bios, bad in rows(directory):
        out.append(f'{{"{sha}", "{driver}", "{file}", "{bios}", {"TRUE" if bad else "FALSE"}}},')
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
